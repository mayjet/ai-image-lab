"""Asset record and manifest schemas."""

from __future__ import annotations

import datetime
from enum import Enum
from pathlib import Path
from typing import Optional

from pydantic import BaseModel, ConfigDict, Field, field_validator


class AssetProvenance(str, Enum):
    """
    Origin classification for each asset.

    user_original  — provided directly by the user; highest trust.
    agent_inferred — extracted/derived by heuristic (e.g. path guess); medium trust.
    agent_derived  — generated by an AI sub-process (e.g. aux image); low trust for
                     final reference; never treat as equivalent to user_original.
    generated_candidate — a FLUX generation candidate awaiting critic evaluation.
    final_output — accepted and optionally upscaled output shown to the user.
    """

    user_original = "user_original"
    agent_inferred = "agent_inferred"
    agent_derived = "agent_derived"
    generated_candidate = "generated_candidate"
    final_output = "final_output"


class AssetRecord(BaseModel):
    """Immutable record for a single asset file."""

    model_config = ConfigDict(frozen=True)

    asset_id: str = Field(..., description="Stable unique identifier (sha256 prefix + slug)")
    sha256: str = Field(..., description="Hex SHA-256 of the raw file bytes")
    provenance: AssetProvenance
    mime_type: str = Field(..., description="e.g. 'image/png'")
    width: Optional[int] = None
    height: Optional[int] = None
    # Path inside the container; None for assets not yet written to disk
    container_path: Optional[str] = None
    # Human-readable role hint from the Markdown (e.g. "顔", "全身")
    role_hint: Optional[str] = None
    created_at: datetime.datetime = Field(
        default_factory=datetime.datetime.utcnow,
        description="UTC creation timestamp",
    )

    @field_validator("sha256")
    @classmethod
    def _validate_hex(cls, v: str) -> str:
        if len(v) != 64 or not all(c in "0123456789abcdef" for c in v.lower()):
            raise ValueError(f"sha256 must be 64 hex chars, got: {v!r}")
        return v.lower()

class AssetManifest(BaseModel):
    """Ordered collection of assets for a single run."""

    run_id: str
    markdown_path: Optional[str] = None
    markdown_sha256: Optional[str] = None
    assets: list[AssetRecord] = Field(default_factory=list)

    def by_id(self, asset_id: str) -> Optional[AssetRecord]:
        for a in self.assets:
            if a.asset_id == asset_id:
                return a
        return None

    def ids_by_provenance(self, provenance: AssetProvenance) -> list[str]:
        return [a.asset_id for a in self.assets if a.provenance == provenance]

    def add(self, record: AssetRecord) -> "AssetManifest":
        """Return a new manifest with the record appended (immutable-style)."""
        return self.model_copy(update={"assets": self.assets + [record]})
